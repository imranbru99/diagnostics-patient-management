    {
        $startTime = microtime(true);

        $prompt = <<<EOT
Extract patient demographic information and ordered laboratory tests from the provided medical requisition slip text:
"{$textOrImagePath}"

Return a valid JSON object strictly matching this schema:
{
  "patient_name": "string or null",
  "phone": "string or null",
  "gender": "male|female|other",
  "age": "integer or null",
  "referring_doctor": "string or null",
  "tests_requested": ["array of test names or codes, e.g. CBC, Lipid Profile, Creatinine"],
  "clinical_history": "string or null",
  "urgency": "normal|urgent|stat"
