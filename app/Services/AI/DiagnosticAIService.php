    /**
     * Generate plain-language summary of a diagnostic report for the patient.
     */
    public function generatePatientSummary(Report $report): string
    {
        $startTime = microtime(true);
        $patient = $report->patient;
        $testName = $report->orderItem->test->name ?? 'Diagnostic Test';

        $valuesSummary = [];
        foreach ($report->values as $val) {
            $paramName = $val->parameter->name ?? 'Parameter';
            $unit = $val->unit ?? '';
            $status = strtoupper($val->flag);
            $valuesSummary[] = "- {$paramName}: {$val->value_numeric} {$unit} (Ref: {$val->reference_range_snapshot}) [{$status}]";
        }
        $valuesText = implode("\n", $valuesSummary);

        $prompt = <<<EOT
You are an empathetic, clinical communicator AI for a patient portal.
Summarize the following laboratory report for the patient in simple, reassuring, and clear language.
Avoid extreme medical jargon or alarming language. Clearly explain what the normal and abnormal findings mean, and remind the patient to discuss with their consulting physician.

Patient Name: {$patient->name}
Age/Gender: {$patient->formatted_age}, {$patient->gender}
Test: {$testName}
Results:
{$valuesText}

Output structure:
1. Overall summary in 2-3 friendly sentences.
2. Key Highlights (Normal & Out-of-Range values explained in simple everyday terms).
3. Recommended Lifestyle or Follow-up steps.
4. Mandatory disclaimer: "This AI summary is for informational purposes only. Please consult your physician for clinical diagnosis."
EOT;

        $response = $this->callAiProvider('report_summarizer', $prompt, $report);

        // Fallback intelligent summary if offline or no API key
        if (empty($response)) {
            $response = $this->generateOfflinePatientSummary($report);
        }

        $latency = (int) ((microtime(true) - $startTime) * 1000);
        $this->logUsage('report_summarizer', $prompt, $response, $latency, $report);

        return $response;
    }

    /**
     * Flag abnormal and critical values against clinical guidelines before pathologist sign-off.
     */
    public function flagAbnormalValues(Report $report): array
    {
        $flags = [];
        foreach ($report->values as $val) {
            if (in_array($val->flag, ['low', 'high', 'critical_low', 'critical_high'])) {
                $flags[] = [
                    'parameter' => $val->parameter->name ?? 'Unknown',
                    'value' => $val->value_numeric,
                    'unit' => $val->unit,
                    'flag' => $val->flag,
                    'reference' => $val->reference_range_snapshot,
                    'severity' => in_array($val->flag, ['critical_low', 'critical_high']) ? 'CRITICAL' : 'WARNING',
                    'clinical_note' => $this->getClinicalFlagNote($val->parameter->name ?? '', $val->flag, $val->value_numeric),
                ];
            }
        }

        return $flags;
    }

    /**
     * Doctor's AI Co-Pilot: Differential considerations and correlation notes.
     * STRICT ADVISORY DISCLAIMER ATTACHED.
     */
    public function generateDoctorCopilotNotes(Report $report): string
    {
        $startTime = microtime(true);
        $abnormals = $this->flagAbnormalValues($report);

        if (empty($abnormals)) {
            return "No clinically abnormal laboratory parameters identified in this panel. Findings appear within standard physiological reference ranges for the specified demographic profile.";
        }

        $abnormalBullets = [];
        foreach ($abnormals as $ab) {
            $abnormalBullets[] = "- {$ab['parameter']}: {$ab['value']} {$ab['unit']} ({$ab['flag']}) [Ref: {$ab['reference']}]";
        }
        $abnormalText = implode("\n", $abnormalBullets);

        $prompt = <<<EOT
You are a Clinical Decision Support (CDSS) AI co-pilot for a medical doctor reviewing a diagnostic panel.
Provide concise, evidence-based differential correlations and potential investigation next steps for these abnormal values.

Test: {$report->orderItem->test->name}
Patient Age/Gender: {$report->patient->formatted_age}, {$report->patient->gender}
Abnormal Parameters:
{$abnormalText}

Rules:
- Be strictly objective and academic.
- Suggest 2-3 potential pathophysiological etiologies to correlate clinically.
- Recommend standard confirmatory or adjunct tests if applicable.
- End with: "ADVISORY NOTE: This analysis is generated by AI decision-support algorithms for licensed medical professionals. It does not constitute a diagnostic determination."
EOT;

        $response = $this->callAiProvider('doctor_copilot', $prompt, $report);

        if (empty($response)) {
            $response = $this->generateOfflineDoctorNotes($report, $abnormals);
        }

        $latency = (int) ((microtime(true) - $startTime) * 1000);
        $this->logUsage('doctor_copilot', $prompt, $response, $latency, $report);

        return $response;
    }

    /**
     * Patient-Facing Scoped RAG Chat: "Ask About Your Report".
     * Strictly bounded to this patient's report ONLY.
     */
    public function chatAboutReport(Report $report, string $question, array $history = []): string
    {
        $startTime = microtime(true);
        $patient = $report->patient;
        $test = $report->orderItem->test;

        $reportContext = "Patient: {$patient->name}, Age: {$patient->formatted_age}, Gender: {$patient->gender}\n";
        $reportContext .= "Test: {$test->name} ({$test->sample_type})\n";
        $reportContext .= "Report Date: " . ($report->verified_at ? $report->verified_at->format('M d, Y') : 'Recent') . "\n";
        $reportContext .= "Results:\n";
        foreach ($report->values as $v) {
            $reportContext .= "- {$v->parameter->name}: {$v->value_numeric} {$v->unit} (Normal Range: {$v->reference_range_snapshot}) [Status: {$v->flag}]\n";
        }
        if ($report->clinical_impression) {
            $reportContext .= "Impression: {$report->clinical_impression}\n";
        }

        $prompt = <<<EOT
You are an intelligent, empathetic medical assistant on the patient portal.
The patient is asking questions about THEIR OWN SPECIFIC laboratory report below.

[PATIENT REPORT CONTEXT]
{$reportContext}
[/PATIENT REPORT CONTEXT]

User Question: "{$question}"

Strict Rules:
1. ONLY answer based on the values in this patient's report.
2. Do NOT diagnose diseases or prescribe medications.
3. Explain medical abbreviations and units clearly in plain terms.
4. If a question is unrelated to this report or asks for dangerous medical advice, politely explain that you can only discuss the findings on this report and advise speaking with their doctor.
5. Keep your tone reassuring, professional, and clear.
EOT;

        $response = $this->callAiProvider('patient_chat', $prompt, $report);

        if (empty($response)) {
            $response = $this->generateOfflineChatReply($report, $question);
        }

        $latency = (int) ((microtime(true) - $startTime) * 1000);
        $this->logUsage('patient_chat', $prompt, $response, $latency, $report);

        return $response;
    }

