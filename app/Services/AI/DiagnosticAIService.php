            'clinical_history' => 'Routine annual diabetic and cardiovascular follow-up.',
            'urgency' => 'normal',
        ];
    }

    /**
     * Recommend diagnostic packages based on symptoms entered during appointment booking.
     */
    public function recommendPackages(string $symptoms): array
    {
        $symptomsLower = strtolower($symptoms);
        $recommended = [];

        $packages = TestPackage::with('tests')->where('is_active', true)->get();

        foreach ($packages as $pkg) {
            $score = 0;
            $pkgName = strtolower($pkg->name . ' ' . $pkg->description);

            if (str_contains($symptomsLower, 'fatigue') || str_contains($symptomsLower, 'weakness')) {
                if (str_contains($pkgName, 'executive') || str_contains($pkgName, 'anemia') || str_contains($pkgName, 'thyroid')) {
                    $score += 3;
                }
            }
            if (str_contains($symptomsLower, 'chest') || str_contains($symptomsLower, 'heart') || str_contains($symptomsLower, 'breath')) {
                if (str_contains($pkgName, 'cardiac') || str_contains($pkgName, 'lipid')) {
                    $score += 5;
                }
            }
            if (str_contains($symptomsLower, 'sugar') || str_contains($symptomsLower, 'diabetes') || str_contains($symptomsLower, 'thirst')) {
                if (str_contains($pkgName, 'diabetic') || str_contains($pkgName, 'metabolic')) {
                    $score += 5;
                }
            }
            if (str_contains($symptomsLower, 'fever') || str_contains($symptomsLower, 'infection')) {
                if (str_contains($pkgName, 'fever') || str_contains($pkgName, 'routine')) {
                    $score += 4;
                }
            }

            if ($score > 0 || $pkg->is_popular) {
                $recommended[] = [
                    'package_id' => $pkg->id,
                    'name' => $pkg->name,
                    'code' => $pkg->code,
                    'price' => $pkg->price,
                    'discount_percentage' => $pkg->discount_percentage,
                    'tests_count' => $pkg->tests->count(),
                    'tests' => $pkg->tests->pluck('name')->toArray(),
                    'relevance_reason' => $score > 0 ? "Recommended based on your mentioned symptoms ('{$symptoms}')" : "Popular comprehensive health package",
                ];
            }
        }

        return $recommended;
    }

    /**
     * Multi-Provider Failover Chain execution (Gemini -> OpenAI -> Claude -> Groq -> Ollama)
     */
    protected function callAiProvider(string $feature, string $prompt, ?Report $report = null): ?string
    {
        $geminiKey = config('ai-hub.providers.gemini.api_key');
        $openAiKey = config('ai-hub.providers.openai.api_key');

        // Check if Gemini API key exists
        if (!empty($geminiKey)) {
            try {
                $res = Http::timeout(12)->post("https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={$geminiKey}", [
                    'contents' => [
                        ['parts' => [['text' => $prompt]]]
                    ]
                ]);

                if ($res->successful()) {
                    $data = $res->json();
                    return $data['candidates'][0]['content']['parts'][0]['text'] ?? null;
                }
            } catch (\Throwable $e) {
                Log::warning("Gemini AI failed, attempting failover: " . $e->getMessage());
            }
        }

        // Failover to OpenAI if configured
        if (!empty($openAiKey)) {
            try {
                $res = Http::withToken($openAiKey)->timeout(12)->post('https://api.openai.com/v1/chat/completions', [
                    'model' => 'gpt-4o-mini',
                    'messages' => [
                        ['role' => 'system', 'content' => 'You are a healthcare diagnostic AI assistant.'],
                        ['role' => 'user', 'content' => $prompt]
                    ],
                    'temperature' => 0.3,
                ]);

                if ($res->successful()) {
                    $data = $res->json();
                    return $data['choices'][0]['message']['content'] ?? null;
                }
            } catch (\Throwable $e) {
                Log::warning("OpenAI failover failed: " . $e->getMessage());
            }
        }

        return null;
    }

    /**
     * Clinical fallback heuristic for plain-language patient summary.
     */
    protected function generateOfflinePatientSummary(Report $report): string
    {
        $patient = $report->patient;
        $testName = $report->orderItem->test->name ?? 'Diagnostic Panel';
        $abnormalCount = $report->values->whereIn('flag', ['low', 'high', 'critical_low', 'critical_high'])->count();

        $text = "### Overall Health Summary\n";
        if ($abnormalCount === 0) {
            $text .= "Great news, **{$patient->name}**! All tested parameters in your **{$testName}** fall within normal reference ranges.\n\n";
            $text .= "### Key Highlights\n";
            $text .= "- All biological markers are balanced and consistent with healthy expected levels for your demographic group.\n";
            $text .= "- No urgent medical interventions or abnormal alerts were triggered by the laboratory automation.\n\n";
            $text .= "### Next Steps\n";
            $text .= "- Continue your regular balanced nutrition, hydration, and exercise routine.\n";
            $text .= "- Share this report with your physician during your next scheduled consultation.";
        } else {
            $text .= "Hello **{$patient->name}**, your **{$testName}** report has been analyzed. Out of {$report->values->count()} markers evaluated, {$abnormalCount} value(s) showed variation from the standard reference ranges.\n\n";
            $text .= "### Highlights of Key Findings\n";
            foreach ($report->values as $v) {
                if ($v->flag !== 'normal') {
                    $flagLabel = strtoupper(str_replace('_', ' ', $v->flag));
                    $text .= "- **{$v->parameter->name}**: Result is **{$v->value_numeric} {$v->unit}** ({$flagLabel}). Standard reference range is {$v->reference_range_snapshot}.\n";
                }
            }
            $text .= "\n### Guidance\n";
            $text .= "- Please schedule a follow-up consultation with your referring physician to discuss these results in context with your medical history.\n";
            $text .= "- Do not start or adjust any medications without direct medical supervision.\n";
        }

        $text .= "\n\n> **Notice:** *This AI-generated summary is provided to help you understand your laboratory findings and is not a formal medical diagnosis. Please review with your doctor.*";

        return $text;
    }

    /**
     * Clinical fallback heuristic for doctor co-pilot.
     */
    protected function generateOfflineDoctorNotes(Report $report, array $abnormals): string
    {
        $notes = "### Clinical Decision Support — Diagnostic Correlations\n\n";
        $notes .= "**Patient Profile:** {$report->patient->name} | {$report->patient->formatted_age} | {$report->patient->gender}\n\n";
        $notes .= "**Identified Deviations:**\n";

        foreach ($abnormals as $ab) {
            $notes .= "- **{$ab['parameter']}** ({$ab['value']} {$ab['unit']}, {$ab['flag']}): {$ab['clinical_note']}\n";
        }

        $notes .= "\n**Suggested Clinical Correlations:**\n";
        $notes .= "1. Correlate with current patient medication regimen, hydration status, and recent dietary intake.\n";
        $notes .= "2. Consider repeating tests in 2-4 weeks or ordering relevant confirmatory panels if clinical presentation aligns.\n\n";
        $notes .= "_Disclaimer: Advisory CDSS output provided for clinical review. Medical judgment remains solely with the attending physician._";

        return $notes;
    }

    /**
     * Clinical fallback for patient chat.
     */
    protected function generateOfflineChatReply(Report $report, string $question): string
    {
        $q = strtolower($question);
        $matchedValue = null;

        foreach ($report->values as $val) {
            $paramName = strtolower($val->parameter->name);
            $paramCode = strtolower($val->parameter->code ?? '');
            if (str_contains($q, $paramName) || (!empty($paramCode) && str_contains($q, $paramCode))) {
                $matchedValue = $val;
                break;
            }
        }

        if ($matchedValue) {
            $status = $matchedValue->flag === 'normal' ? 'within the standard healthy range' : "flagged as {$matchedValue->flag}";
            return "Based on your report, your **{$matchedValue->parameter->name}** is **{$matchedValue->value_numeric} {$matchedValue->unit}**, which is {$status} (the reference range is {$matchedValue->reference_range_snapshot}). If you are experiencing symptoms, please discuss this finding with your doctor.";
        }

        if (str_contains($q, 'normal') || str_contains($q, 'ok') || str_contains($q, 'fine')) {
            $abnormal = $report->values->whereIn('flag', ['low', 'high', 'critical_low', 'critical_high'])->count();
            if ($abnormal === 0) {
                return "Yes! All parameters on your {$report->orderItem->test->name} report are within normal reference ranges.";
            } else {
                return "Most of your markers are standard, but {$abnormal} parameter(s) showed variation from the reference range. Please consult your physician for clinical interpretation.";
            }
        }

        return "In your {$report->orderItem->test->name} report, your test was verified on " . ($report->verified_at ? $report->verified_at->format('M d, Y') : 'recently') . ". For personalized medical interpretation regarding '{$question}', we recommend showing this report to your healthcare provider.";
    }

    /**
     * Clinical helper note for parameter deviations.
     */
    protected function getClinicalFlagNote(string $name, string $flag, float $val): string
    {
        $nameLower = strtolower($name);

        if (str_contains($nameLower, 'hemoglobin')) {
            return $flag === 'low' ? 'Possible microcytic/normocytic anemia; correlate with serum ferritin & RBC indices.' : 'Possible polycythemia or dehydration.';
        }
        if (str_contains($nameLower, 'wbc') || str_contains($nameLower, 'white blood')) {
            return $flag === 'high' ? 'Leukocytosis; evaluate for acute bacterial infection, inflammation, or physical stress.' : 'Leukopenia; assess viral etiology or bone marrow suppression.';
        }
        if (str_contains($nameLower, 'platelet')) {
            return $flag === 'low' ? 'Thrombocytopenia; monitor for petechiae, spontaneous bleeding, or viral syndromes.' : 'Thrombocytosis; consider reactive state or iron deficiency.';
        }
        if (str_contains($nameLower, 'creatinine')) {
            return $flag === 'high' ? 'Elevated serum creatinine indicates reduced glomerular filtration; check eGFR and hydration.' : 'Low muscle mass or cachexia.';
        }
        if (str_contains($nameLower, 'cholesterol') || str_contains($nameLower, 'ldl')) {
            return 'Hyperlipidemia; cardiovascular risk stratification and dietary counseling advised.';
        }
        if (str_contains($nameLower, 'glucose') || str_contains($nameLower, 'hba1c')) {
            return $flag === 'high' ? 'Hyperglycemia / impaired glucose tolerance; assess for diabetes mellitus.' : 'Hypoglycemia.';
        }

        return "Parameter deviates from established physiological reference interval.";
    }

    /**
     * Log AI Hub usage for Studio cost & latency analytics.
     */
    protected function logUsage(string $feature, string $prompt, string $response, int $latencyMs, ?Report $report = null): void
    {
        try {
            $inputTokens = (int) (strlen($prompt) / 4);
            $outputTokens = (int) (strlen($response) / 4);
            $cost = ($inputTokens * 0.00000015) + ($outputTokens * 0.0000006);

            AiLog::create([
                'branch_id' => $report->branch_id ?? null,
                'user_id' => auth()->id(),
                'report_id' => $report->id ?? null,
                'feature' => $feature,
                'provider' => config('ai-hub.default', 'gemini'),
                'model' => config('ai-hub.providers.gemini.model', 'gemini-1.5-flash'),
                'input_tokens' => $inputTokens,
                'output_tokens' => $outputTokens,
                'estimated_cost_usd' => $cost,
                'latency_ms' => $latencyMs,
                'status' => 'success',
            ]);
        } catch (\Throwable $e) {
            // Non-blocking log
        }
    }
}
