EOT;

        $response = $this->callAiProvider('ocr_requisition', $prompt);

        if (!empty($response)) {
            $decoded = json_decode($response, true);
            if (is_array($decoded)) {
                return $decoded;
            }
        }

        // Realistic OCR parser fallback
        return [
